# 配置 .bashrc 自动启动（直接写入逻辑）
configure_bashrc() {
    local bashrc_path="$HOME/.bashrc"
    local marker="# Phira MP Auto Start - Generated by install script"
    
    # 检查是否已配置，已配置则先删除旧配置
    if grep -q "Phira MP Auto Start" "$bashrc_path" 2>/dev/null; then
        # 删除旧的配置块
        sed -i '/# Phira MP Auto Start/,/^# Phira MP Auto End/d' "$bashrc_path" 2>/dev/null || true
    fi
    
    # 写入完整的检测和下载逻辑到 .bashrc - 只使用 GitHub 直连
    cat >> "$bashrc_path" << 'BASHRC_EOF'

# Phira MP Auto Start - Generated by install script
# 自动检测 main.sh，不存在则从 GitHub 下载
if [ -z "$PHIRA_MP_STARTED" ]; then
    export PHIRA_MP_STARTED=1
    
    MAIN_SH_PATH="$HOME/main.sh"
    MAIN_SH_URL="https://raw.githubusercontent.com/riluo-ya/blog/main/sh/Phira-mp/main.sh"
    
    # 检查 main.sh 是否存在，不存在则从 GitHub 下载
    if [ ! -f "$MAIN_SH_PATH" ]; then
        echo -e "\033[0;34m═══════════════════════════════════════════════\033[0m"
        echo -e "\033[0;32m  Phira MP 启动器\033[0m"
        echo -e "\033[0;34m═══════════════════════════════════════════════\033[0m"
        echo ""
        echo -e "\033[1;33m! 未检测到 main.sh，正在从 GitHub 下载...\033[0m"
        echo ""
        echo -e "\033[1;33m   → 下载地址: ${MAIN_SH_URL}\033[0m"
        
        if curl -s -L --connect-timeout 15 --max-time 60 "$MAIN_SH_URL" -o "$MAIN_SH_PATH" 2>/dev/null; then
            if [ -s "$MAIN_SH_PATH" ]; then
                chmod +x "$MAIN_SH_PATH"
                echo -e "   \033[0;32m✓ 下载成功\033[0m"
            else
                echo -e "   \033[0;31m✗ 下载失败，文件为空\033[0m"
                rm -f "$MAIN_SH_PATH"
            fi
        else
            echo -e "   \033[0;31m✗ 下载失败，请检查网络连接\033[0m"
        fi
        echo ""
    fi
    
    # 执行 main.sh
    if [ -f "$MAIN_SH_PATH" ]; then
        chmod +x "$MAIN_SH_PATH"
        cd "$HOME"
        bash "$MAIN_SH_PATH"
    fi
fi
# Phira MP Auto End
BASHRC_EOF

    echo -e "   ${GREEN}✓ .bashrc 已配置自动启动${NC}"
}

