# 进度条
show_progress() {
    local current=$1
    local total=$2
    local title=$3
    local percent=$(( current * 100 / total ))
    local filled=$(( percent / 2 ))
    local empty=$(( 50 - filled ))
    
    echo -e "${CYAN}【步骤 ${current}/${total}】${NC} ${WHITE}${title}${NC}"
    echo -ne "${GREEN}["
    printf "%0.s█" $(seq 1 $filled)
    printf "%0.s░" $(seq 1 $empty)
    echo -e "] ${percent}%${NC}"
    echo ""
}

