set -e
# ==================== 颜色定义 ====================
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
PURPLE='\033[0;35m'
CYAN='\033[0;36m'
WHITE='\033[1;37m'
NC='\033[0m' # No Color
# ==================== 全局变量 ====================
TOTAL_STEPS=7
CURRENT_STEP=0
INSTALL_DIR="$HOME/tphira-mp"
MAIN_SH_URL="https://raw.githubusercontent.com/riluo-ya/blog/main/sh/Phira-mp/main.sh"
# ==================== 工具函数 ====================
# 打印横幅
