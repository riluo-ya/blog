    clear
    echo -e "${PURPLE}"
    echo "╔══════════════════════════════════════════════════════════════╗"
    echo "║                                                              ║"
    echo "║   ██████╗ ██╗  ██╗██╗██████╗  █████╗     ███╗   ███╗██████╗  ║"
    echo "║   ██╔══██╗██║  ██║██║██╔══██╗██╔══██╗    ████╗ ████║██╔══██╗ ║"
    echo "║   ██████╔╝███████║██║██████╔╝███████║    ██╔████╔██║██████╔╝ ║"
    echo "║   ██╔═══╝ ██╔══██║██║██╔══██╗██╔══██║    ██║╚██╔╝██║██╔═══╝  ║"
    echo "║   ██║     ██║  ██║██║██║  ██║██║  ██║    ██║ ╚═╝ ██║██║      ║"
    echo "║   ╚═╝     ╚═╝  ╚═╝╚═╝╚═╝  ╚═╝╚═╝  ╚═╝    ╚═╝     ╚═╝╚═╝      ║"
    echo "║                                                              ║"
    echo "║            Phira 联机服务器 - 一键安装脚本                    ║"
    echo "║                    for Termux                                ║"
